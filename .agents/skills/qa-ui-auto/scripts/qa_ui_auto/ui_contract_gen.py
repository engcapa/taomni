"""Generate executable focus and geometry cases for registered private dialogs."""
from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

import yaml

REGISTRY = Path("qa-ui-auto-tests/fixtures/ui-contract-registry.yaml")
CASES = Path("qa-ui-auto-tests/cases")
PREFIX = "TC-UIC-DLG-"
HEADER = "# Generated by qa_ui_auto.ui_contract_gen from ui-contract-registry.yaml.\n"


def dialog_case(entry: dict) -> dict:
    slug = entry["slug"]
    if not re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", slug):
        raise ValueError(f"Invalid dialog slug {slug!r}")

    def selector(key: str) -> str:
        return f'[data-testid={json.dumps(entry[key])}]'

    panel = selector("panel")
    first = selector("first")
    last = selector("last")
    steps = list(entry["open"])
    if not steps:
        raise ValueError(f"{slug} needs a product entry")
    requirements = []
    opening = len(steps)

    def step(verb: str, args) -> int:
        steps.append({verb: args})
        return len(steps)

    def requirement(name, text, rules, actions, checks):
        requirements.append({
            "id": name, "requirement": text, "ui_standard": rules, "actions": actions,
            "checkpoints": [{"step": n, "expectation": message} for n, message in checks],
            "results": [n for n, _ in checks],
        })

    step("wait_for", panel + '[role="dialog"][aria-modal="true"]')
    title = step("assert_labelledby_text", {"selector": panel, "equals": entry["heading"]})
    geometry = step("assert_element_geometry", {
        "selector": panel, "min_width": 1, "min_height": 1, "viewport_margin": 0,
    })
    initial = selector("initial") if "initial" in entry else first
    focused = step("assert_focus_on", initial)
    requirement("open", "The entry opens a labelled modal within the viewport and focuses its first control." if initial == first
                else "The entry opens a labelled modal within the viewport and focuses its editing field.",
                ["UI-DLG-03", "UI-DLG-06"], [opening],
                [(title, "The modal references the expected title."), (geometry, "All edges fit the viewport."),
                 (focused, "The initial control has focus." if initial != first else "The first control has focus.")])
    if initial != first:
        navigation = entry.get("to_first")
        if not navigation or any(key not in ("Tab", "Shift+Tab") for key in navigation):
            raise ValueError(f"{slug} must give the keyboard path from initial focus to its first control")
        actions = [step("press", key) for key in navigation]
        edge = step("assert_focus_on", first)
        requirement("first-control", "The first control is reachable from the initial editing field.",
                    ["UI-DLG-04"], actions, [(edge, "Focus reaches the leading control.")])

    back = step("press", "Shift+Tab")
    end = step("assert_focus_on", last)
    forward = step("press", "Tab")
    start = step("assert_focus_on", first)
    # Return to the editing field before cancelling. A keyboard-focused icon
    # at the edge of the cycle may have its own dismissible tooltip.
    if initial != first:
        for key in reversed(navigation):
            step("press", "Tab" if key == "Shift+Tab" else "Shift+Tab")
        step("assert_focus_on", initial)
    close = step("press", "Escape")
    gone = step("assert_not_visible", panel)
    returned = step("assert_focus_on", selector("return_to"))
    requirement("focus-cycle", "Tab wraps at both ends. Escape closes this form and restores the logical opener.",
                ["UI-DLG-04", "UI-DLG-07"], [back, forward, close],
                [(end, "Reverse Tab reaches the last action."), (start, "Forward Tab returns to the first control."),
                 (gone, "The form is closed."), (returned, "The logical opener has focus.")])
    step("assert_no_runtime_errors", None)
    return {
        "id": PREFIX + slug, "title": entry["title"], "covers": entry["covers"],
        "fixtures": entry["fixtures"], "modes": ["browser", "native"], "tags": ["ui-contract", "auto-generated"],
        "ui_standard": sorted({rule for req in requirements for rule in req["ui_standard"]}),
        "steps": steps,
        "verification": {"review": "reviewed", "requirements": requirements,
                         "visual": [{"check": "Viewport fit", "method": "automated",
                                     "reason": "Measures the rendered dialog bounds."}],
                         "native": [{"check": "Packaged WebView", "method": "automated",
                                     "reason": "Checks actual focus and geometry in the active desktop document."}]},
    }


def sync(registry: Path, cases: Path, check: bool) -> list[str]:
    entries = yaml.safe_load(registry.read_text(encoding="utf-8"))["dialogs"]
    expected = {}
    for entry in entries:
        case = dialog_case(entry)
        path = cases / (case["id"] + ".testcase.yaml")
        if path in expected:
            raise ValueError(f"Duplicate dialog entry {entry['slug']}")
        expected[path] = HEADER + yaml.safe_dump(case, sort_keys=False, allow_unicode=True, width=110)
    errors = []
    for path, content in expected.items():
        if path.exists() and path.read_text(encoding="utf-8") == content:
            continue
        if check:
            errors.append(f"Regenerate {path}")
        else:
            path.write_text(content, encoding="utf-8")
    errors.extend(f"Remove unregistered case {path}" for path in sorted(cases.glob(PREFIX + "*.testcase.yaml"))
                  if path not in expected)
    return errors


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    failures = sync(REGISTRY, CASES, parser.parse_args().check)
    for failure in failures:
        print(failure)
    raise SystemExit(bool(failures))
