import type { CodeWorkspaceFileRef } from "../../../../types";
import type { WorkspaceEntry } from "../../../../lib/editor/workspace";
import type { LspDocumentStatus, LspDiagnostic } from "../../../../lib/editor/lsp";
import type { GitChange } from "../../../../lib/git";
import type { OpenFileViewModel } from "../editorGroupTypes";
import type { FileTreeViewMode } from "../FileTreePane";
import type { DiagnosticScope } from "../diagnosticScopeModel";

export type MermaidApi = typeof import("mermaid").default;

export type OpenFileState = OpenFileViewModel;

export type TreeViewMode = FileTreeViewMode;

export type MarkdownViewMode = "edit" | "preview" | "split";

/** Custom LSP command shape shared by workspace sessions and Settings. */
export interface LspCustomCommandConfig {
  command: string;
  args: string;
}

export interface WorkspaceBuildRunTool {
  executable: string;
}

export interface WorkspaceMavenRunOptions {
  /** Extra JVM options, one option per item, used only by Maven Java Run tasks. */
  jvmArgs: string[];
  /** Inherit safe JPMS options declared in the Maven test-plugin argLine. */
  inheritProjectJvmArgs: boolean;
}

export interface WorkspaceDebugStepFilters {
  enabled: boolean;
  /** Class or package patterns to step over (e.g. java.*, javax.*, sun.*, com.sun.*). */
  patterns: string[];
  /** Skip synthetic methods generated by compiler. */
  skipSynthetics: boolean;
  /** Skip class static initializers (<clinit>). */
  skipStaticInitializers: boolean;
  /** Skip class constructors (<init>). */
  skipConstructors: boolean;
}

export interface WorkspaceBuildRunTools {
  tools: Record<string, WorkspaceBuildRunTool>;
  mavenRun: WorkspaceMavenRunOptions;
  stepFilters?: WorkspaceDebugStepFilters;
}

export interface DirectoryState {
  entries: WorkspaceEntry[];
  loaded: boolean;
  loading: boolean;
  error: string | null;
}

export interface CompactChainState {
  path: string;
  entries: WorkspaceEntry[];
  loading: boolean;
  error: string | null;
}

export interface LspFileState {
  status: LspDocumentStatus | null;
  diagnostics: LspDiagnostic[];
  diagnosticScope: DiagnosticScope | null;
  syncing: boolean;
  syncedText: string | null;
  error: string | null;
  /** Increments when a failed condition reappears after being cleared. */
  errorGeneration: number;
}

export type TreeSelection =
  | { kind: "root"; rootId: string; }
  | { kind: "dir"; rootId: string; path: string; }
  | { kind: "file"; ref: CodeWorkspaceFileRef; };

export interface WorkspaceTreeCommandPayload {
  selection?: TreeSelection;
  directory?: { rootId: string; path: string; };
  rootId?: string;
  path?: string;
}

export interface FlatFilesState {
  entries: WorkspaceEntry[];
  loading: boolean;
  loaded: boolean;
  error: string | null;
  truncated: boolean;
}

export interface WorkspaceGitSnapshotState {
  changes: GitChange[];
  headOid: string | null;
  currentBranch: string | null;
  ahead: number;
  behind: number;
  loading: boolean;
  error: string | null;
}

/**
 * An SDK / dependency source delivered by a language server or read from an
 * archive instead of the normal file system.
 */
export interface LibraryBufferInfo {
  uri: string;
  /** Display name, e.g. `String.java`. */
  title: string;
  /** `package · jar/module` label for the tab subtitle. */
  container: string | null;
  languageId: string;
  /** Project file the jump started from; selects the language-server session. */
  originFilePath: string;
  originRootPath: string | null;
  /** True when the buffer is decompiled bytecode (offer "Download sources"). */
  decompiled?: boolean;
}

export interface ParsedFsPath {
  prefix: string;
  segments: string[];
  absolute: boolean;
}
