export const DEFAULT_COLUMN_FILTER: ColumnFilterConfig = { text: "", mode: "fuzzy", selectedValues: [] };

export const DISTINCT_FILTER_VALUE_LIMIT = 100;


export const EXPORT_DEFAULTS_KEY = "taomni.db.exportGrid.defaults.v1";

export const EXPORT_HISTORY_KEY = "taomni.db.exportGrid.fileHistory.v1";


export function defaultExportColumns(columns: DbColumn[]): ExportColumnConfig[] {
  return columns.map((column, index) => ({
    id: `col-${index}-${column.name}`,
    export: true,
    name: column.name,
    label: column.name,
    type: column.type,
    isText: /(char|text|clob|string|uuid|json|xml)/i.test(column.type),
    textFunction: "none",
    valueTemplate: "${value}$",
  }));
}


export function readStoredExportOptions(): ExportOptions {
  try {
    const raw = localStorage.getItem(EXPORT_DEFAULTS_KEY);
    if (!raw) return DEFAULT_EXPORT_OPTIONS;
    return { ...DEFAULT_EXPORT_OPTIONS, ...(JSON.parse(raw) as Partial<ExportOptions>) };
  } catch {
    return DEFAULT_EXPORT_OPTIONS;
  }
}


export function readExportFileHistory(): string[] {
  try {
    const parsed = JSON.parse(localStorage.getItem(EXPORT_HISTORY_KEY) ?? "[]");
    return Array.isArray(parsed) ? parsed.filter((value): value is string => typeof value === "string") : [];
  } catch {
    return [];
  }
}


export function writeExportFileHistory(paths: string[]): void {
  try {
    localStorage.setItem(EXPORT_HISTORY_KEY, JSON.stringify(paths.slice(0, 12)));
  } catch {
    /* ignore */
  }
}
