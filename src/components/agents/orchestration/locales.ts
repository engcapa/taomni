export type OrchKey = keyof typeof en;
export type OrchTranslate = (key: OrchKey, params?: Record<string, string | number>) => string;
export function useOrchT(): OrchTranslate {
  const locale = useSyncExternalStore(subscribeLocale, getLocale, getLocale);
  return useCallback((key, params) => {
    const text = (locale === "zh-CN" ? zh : en)[key];
    return text.replace(/\{(\w+)\}/g, (match, name: string) => String(params?.[name] ?? match));
  }, [locale]);
}
